/**
 * One entry of the services accordion. `what` opens, the optional `list` is the
 * scannable middle (symptoms for a condition, findings for an examination) and
 * `close` is the last word — treatment, or how the examination is performed.
 * Both the list and the closing block carry their own label, because an
 * examination has no symptoms and a condition has no procedure time.
 */
export type Detail = {
  readonly name: string;
  readonly what: string;
  readonly list?: { readonly label: string; readonly items: readonly string[] };
  readonly close: { readonly label: string; readonly body: string };
};

export type Service = {
  readonly slug: string;
  readonly title: string;
  readonly lead: string;
  readonly items: readonly Detail[];
};

